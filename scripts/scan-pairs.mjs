// Lists the pair tokens Pons V2 accepts, from the factory's own events, and
// writes src/config/pairs.generated.ts. Every candidate is re-checked with
// approvedPairTokens() and its name/symbol/decimals are read from chain.
// Usage: node scripts/scan-pairs.mjs [rpc-url]   (default: the public RPC)
import { writeFileSync } from "node:fs";
import { decodeAbiParameters, encodeFunctionData, keccak256, toHex } from "viem";

const RPC = process.argv[2] || process.env.ROBINHOOD_RPC_URL || "https://rpc.mainnet.chain.robinhood.com";
const FACTORY = "0x7eD598BcEf8bd9Edd8C97A195C6d13f40801EC7e";
const TOPIC = keccak256(toHex("PairTokenApprovalUpdated(address,bool)"));
const SPAN = 3_000_000;

async function rpc(method, params) {
  for (let n = 0; n < 4; n++) {
    try {
      const res = await fetch(RPC, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
      const j = await res.json();
      if (j.error) throw new Error(j.error.message);
      return j.result;
    } catch (e) {
      if (n === 3) throw e;
      await new Promise((r) => setTimeout(r, 800));
    }
  }
}

const head = Number(BigInt(await rpc("eth_blockNumber", [])));
// The public node keeps no old state, but it serves logs from genesis.
const lo = Number(process.env.FROM_BLOCK || 0);
console.log("scanning blocks", lo, "to", head);

const state = new Map();
for (let from = lo; from <= head; from += SPAN) {
  const to = Math.min(head, from + SPAN - 1);
  const logs = await rpc("eth_getLogs", [{ address: FACTORY, topics: [TOPIC], fromBlock: `0x${from.toString(16)}`, toBlock: `0x${to.toString(16)}` }]);
  for (const l of logs) state.set(`0x${l.topics[1].slice(26)}`, BigInt(l.data) === 1n);
}
const abi = [
  { type: "function", name: "approvedPairTokens", stateMutability: "view", inputs: [{ type: "address" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "name", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
];
const call = async (to, fn, args = []) => {
  const data = encodeFunctionData({ abi, functionName: fn, args });
  const raw = await rpc("eth_call", [{ to, data }, "latest"]);
  return decodeAbiParameters(abi.find((f) => f.name === fn).outputs, raw)[0];
};
const out = [];
for (const [addr, on] of state) {
  if (!on) continue;
  if (!(await call(FACTORY, "approvedPairTokens", [addr]))) continue;
  const [name, symbol, decimals] = await Promise.all([call(addr, "name"), call(addr, "symbol"), call(addr, "decimals")]);
  const clean = (s) => String(s).replace(/[^\x20-\x7E]/g, "").replace(/\s+Robinhood Token$/, "").replace(/\s+$/, "").replace(/\s*-?\s*$/, "").slice(0, 48);
  out.push({ address: addr, symbol: clean(symbol), name: clean(name.replace("•", "")), decimals: Number(decimals) });
}
out.sort((a, b) => a.symbol.localeCompare(b.symbol));
const file = `// Generated by scripts/scan-pairs.mjs on ${new Date().toISOString().slice(0, 10)} from PairTokenApprovalUpdated
// events of the Pons V2 factory, each re-checked with approvedPairTokens(). The launch panel
// re-checks the chosen pair live before every launch. Regenerate: npm run scan-pairs
export type PairToken = { address: string; symbol: string; name: string; decimals: number };
export const PAIR_TOKENS: PairToken[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../src/config/pairs.generated.ts", import.meta.url), file);
console.log("approved pairs:", out.length, out.map((p) => p.symbol).join(" "));
